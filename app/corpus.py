def generate_corpus(company: str, out_dir: str, seed: int = 38) -> dict:
    """Generate the 24-document corpus into out_dir and return the manifest:
    {"company", "seed", "generated": [{doc_id, type, filename, planted_trap,
    ground_truth}]} -- ground_truth carries the exact field values the
    certification gate verifies extraction against. Also written to
    {out_dir}/manifest.json."""
    rng = random.Random(seed)
    os.makedirs(out_dir, exist_ok=True)
    builders = (_build_invoices, _build_pos, _build_claims, _build_qirs,
                _build_incidents, _build_hr, _build_manifests, _build_marketing,
                _build_contracts)
    generated = []
    for dtype, build in zip(TAXONOMY, builders):  # TAXONOMY declaration order
        for doc_id, story, gt, planted in build(company, rng):
            filename = f"{doc_id}.pdf"
            _render(os.path.join(out_dir, filename), company, story)
            generated.append({"doc_id": doc_id, "type": dtype, "filename": filename,
                              "planted_trap": planted, "ground_truth": gt})
    counts = {t: sum(1 for e in generated if e["type"] == t) for t in TAXONOMY}
    if len(generated) != 24 or any(counts[t] != TAXONOMY[t]["count"] for t in TAXONOMY):
        raise RuntimeError(f"corpus shape mismatch: {counts}")
    manifest = {"company": company, "seed": seed, "generated": generated}
    with open(os.path.join(out_dir, "manifest.json"), "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2)
    return manifest

