def _d2(cents: int) -> str:
    return f"{cents // 100}.{cents % 100:02d}"

def _usd(cents: int) -> str:
    return f"${cents // 100:,}.{cents % 100:02d}"

def _phone(rng: random.Random) -> str:
    return f"555-01{rng.randrange(100):02d}"  # canonical fictional exchange

def _email(name: str) -> str:
    return name.lower().replace(" ", ".") + "@example.com"

def _add_months(d: date, months: int) -> date:
    m = d.month - 1 + months
    y, m = d.year + m // 12, m % 12 + 1
    return date(y, m, min(d.day, calendar.monthrange(y, m)[1]))

def _invariant_canvas(*args, **kwargs) -> Canvas:
    kwargs["invariant"] = 1  # fixed CreationDate + doc ID -> byte-stable PDFs
    return Canvas(*args, **kwargs)

def _page_decorator(company: str):
    def draw(canv, _doc):
        w, h = LETTER
        canv.saveState()
        canv.setFont("Helvetica-Bold", 10)  # company name: plain text header only
        canv.setFillColor(INK)
        canv.drawString(0.75 * inch, h - 0.55 * inch, company)
        canv.setFont("Helvetica", 7.5)
        canv.setFillColor(GREY)
        canv.drawRightString(w - 0.75 * inch, h - 0.55 * inch,
                             f"Synthetic demo corpus - page {canv.getPageNumber()}")
        canv.setLineWidth(0.75)
        canv.setStrokeColor(RULE)
        canv.line(0.75 * inch, h - 0.63 * inch, w - 0.75 * inch, h - 0.63 * inch)
        # Watermark lives in the margin bands, not over the body: a giant center
        # overlay interleaves with table text when pages are machine-parsed.
        canv.setFont("Helvetica-Bold", 15)
        canv.setFillColor(WMARK)
        canv.drawCentredString(w / 2, h - 0.92 * inch, WATERMARK_TEXT)
        canv.drawCentredString(w / 2, 0.62 * inch, WATERMARK_TEXT)
        canv.restoreState()
        canv.saveState()
        canv.setFont("Helvetica-Oblique", 7.5)
        canv.setFillColor(GREY)
        canv.drawCentredString(w / 2, 0.45 * inch, FOOTER_TEXT)
        canv.restoreState()
    return draw

def _render(path: str, company: str, story: list) -> None:
    doc = SimpleDocTemplate(path, pagesize=LETTER, leftMargin=0.75 * inch,
                            rightMargin=0.75 * inch, topMargin=1.0 * inch,
                            bottomMargin=0.85 * inch, title=os.path.basename(path)[:-4],
                            author="DocFlow synthetic corpus generator")
    deco = _page_decorator(company)
    doc.build(story, onFirstPage=deco, onLaterPages=deco, canvasmaker=_invariant_canvas)

def _table(data, widths, styles, **kw) -> Table:
    t = Table(data, colWidths=widths, **kw)
    t.setStyle(TableStyle(styles + [("TOPPADDING", (0, 0), (-1, -1), 3),
                                    ("BOTTOMPADDING", (0, 0), (-1, -1), 3)]))
    return t

def _kv(pairs) -> Table:
    rows = [[Paragraph(f"<b>{_esc(str(k))}</b>", S_CELL), Paragraph(_esc(str(v)), S_CELL)]
            for k, v in pairs]
    return _table(rows, [1.9 * inch, 4.6 * inch],
                  [("VALIGN", (0, 0), (-1, -1), "TOP"),
                   ("LINEBELOW", (0, 0), (-1, -1), 0.4, colors.Color(0.87, 0.87, 0.87))])

def _grid(header, rows, widths) -> Table:
    return _table([header] + rows, widths,
                  [("FONT", (0, 0), (-1, 0), "Helvetica-Bold", 8.5),
                   ("FONT", (0, 1), (-1, -1), "Helvetica", 9),
                   ("BACKGROUND", (0, 0), (-1, 0), HEADBG),
                   ("GRID", (0, 0), (-1, -1), 0.4, RULE),
                   ("ALIGN", (1, 0), (-1, -1), "RIGHT"),
                   ("VALIGN", (0, 0), (-1, -1), "TOP")], repeatRows=1)

def _items_grid(items) -> Table:
    return _grid(["Description", "Qty", "Unit price", "Amount"],
                 [[Paragraph(_esc(d), S_CELL), str(q), _usd(p), _usd(q * p)] for d, q, p in items],
                 [3.9 * inch, 0.7 * inch, 1.2 * inch, 1.2 * inch])

def _totals(rows) -> Table:
    return _table([[label, _usd(c)] for label, c in rows], [1.7 * inch, 1.3 * inch],
                  [("FONT", (0, 0), (-1, -1), "Helvetica", 9),
                   ("FONT", (0, -1), (-1, -1), "Helvetica-Bold", 9.5),
                   ("ALIGN", (1, 0), (1, -1), "RIGHT"),
                   ("LINEABOVE", (0, -1), (-1, -1), 0.8, INK)], hAlign="RIGHT")

def _items_gt(items):
    return [{"description": d, "qty": q, "unit_price": _d2(p), "amount": _d2(q * p)}
            for d, q, p in items]

def _form(title, subtitle, pairs, *tail):
    """Story skeleton shared by every form-style document."""
    return [Paragraph(title, S_TITLE), Paragraph(subtitle, S_SUB), _kv(pairs), *tail]

def _sec(heading, body):
    return [Spacer(0, 10), Paragraph(heading, S_H2), Paragraph(_esc(body), S_BODY)]

def _invoice(inv_id, company, vendor, inv_date, items, contact, phone, planted):
    subtotal = sum(q * p for _, q, p in items)
    tax = (subtotal * 825 + 5000) // 10000  # 8.25 percent, half-up, exact cents
    total, due = subtotal + tax, inv_date + timedelta(days=30)
    story = _form("INVOICE", f"{_esc(vendor)} - {_esc(VENDORS[vendor])}",
                  [("Invoice number", inv_id), ("Invoice date", inv_date.isoformat()),
                   ("Payment due", due.isoformat()), ("Terms", "Net 30"),
                   ("Bill to", f"{company}, Receiving Dept, {FICTIONAL_SITE}"),
                   ("Vendor contact", f"{contact} - {_email(contact)} - {phone}")],
                  Spacer(0, 14), _items_grid(items), Spacer(0, 8),
                  _totals([("Subtotal", subtotal), ("Tax (8.25%)", tax), ("Total due", total)]))
    gt = {"invoice_number": inv_id, "vendor": vendor, "invoice_date": inv_date.isoformat(),
          "due_date": due.isoformat(), "subtotal": _d2(subtotal), "tax": _d2(tax),
          "total": _d2(total), "line_items": _items_gt(items),
          "serial_numbers": sorted({s for d, _, _ in items for s in re.findall(r"SN-\d+", d)})}
    return inv_id, story, gt, planted

